#!/usr/bin/env python3
# Generate src/avr/chip/<mcu>.rs from avr-libc's <avr/io.h> for one -mmcu: every
# register (_SFR_IO8 / _SFR_MEM8 / _SFR_MEM16: a pointer to a volatile Reg at its
# data space address; `addr::NAME` the address as an integer), every integer macro
# (bit numbers, RAMEND, ...) and every interrupt vector (an `avr_vector!` arm
# giving its __vector_N symbol). The values come from avr-gcc, never typed in by
# hand: the macros from its preprocessor, the integer ones computed by it.
#
#   gen_avr_regs.py <mcu> <out.rs>
#   e.g. gen_avr_regs.py atmega2560 src/avr/chip/atmega2560.rs
import re, subprocess, sys

mcu, out = sys.argv[1:3]


def gcc(args, src):
    return subprocess.run(['avr-gcc', '-mmcu=' + mcu] + args + ['-x', 'c', '-'], input=src,
                          capture_output=True, text=True)


macros = {}
for line in gcc(['-dM', '-E'], '#include <avr/io.h>\n').stdout.splitlines():
    m = re.match(r'#define (\w+) (.*)$', line)
    if m:
        macros[m.group(1)] = m.group(2).strip()

# (an io register's data space address: its io address plus __SFR_OFFSET)
offset = int(macros['__SFR_OFFSET'], 0)
num = r'(0[xX][0-9a-fA-F]+|\d+)'
regs, vectors, cands = [], [], []
for name, v in sorted(macros.items()):
    if name.startswith('_') and name != '__SFR_OFFSET':
        continue
    m = re.fullmatch(r'_SFR_(IO|MEM)(8|16) *\(' + num + r'\)', v)
    if m:
        addr = int(m.group(3), 0) + (offset if m.group(1) == 'IO' else 0)
        regs.append((name, 'u' + m.group(2), addr))
        continue
    m = re.fullmatch(r'_VECTOR *\(' + num + r'\)', v)
    if m:
        vectors.append((name, int(m.group(1), 0)))
        continue
    if v and '"' not in v:
        cands.append(name)

# the integer macros: avr-gcc computes each as a constant (those that are
# not integer constant expressions fail and are left out)
consts = {}
while cands:
    src = '#include <avr/io.h>\n' + ''.join(
        'const unsigned long long kaliru_v_%s = (unsigned long long)(%s);\n' % (n, n) for n in cands)
    r = gcc(['-S', '-O2', '-o', '-'], src)
    if r.returncode:
        bad = {cands[int(m.group(1)) - 2] for m in re.finditer(r'<stdin>:(\d+):\d+: error', r.stderr)
               if 0 <= int(m.group(1)) - 2 < len(cands)}
        if not bad:
            sys.exit(r.stderr)
        cands = [n for n in cands if n not in bad]
        continue
    # (each value: its label, then .byte / .word / .long / .quad pieces,
    # little endian)
    cur, parts = None, []
    for line in r.stdout.splitlines() + ['end:']:
        m = re.match(r'kaliru_v_(\w+):$', line)
        if m or re.match(r'\S.*:$', line):
            if cur is not None:
                v, shift = 0, 0
                for size, x in parts:
                    v |= (x & ((1 << (8 * size)) - 1)) << shift
                    shift += 8 * size
                consts[cur] = v
            cur, parts = (m.group(1) if m else None), []
            continue
        d = re.match(r'\s+\.(byte|word|long|quad)\s+(-?\w+)', line)
        if cur is not None and d:
            parts.append(({'byte': 1, 'word': 2, 'long': 4, 'quad': 8}[d.group(1)], int(d.group(2), 0)))
        elif cur is not None and re.match(r'\s+\.zero\s+(\d+)', line):
            parts.append((int(re.match(r'\s+\.zero\s+(\d+)', line).group(1)), 0))
    break

with open(out, 'w', newline='\n') as f:
    f.write('// Generated by tools/gen_avr_regs.py from avr-libc <avr/io.h> (-mmcu=%s): do not edit.\n' % mcu)
    f.write('use crate::reg::Reg;\n\n')
    for name, t, addr in regs:
        f.write('pub const %s: *mut Reg<%s> = 0x%x as *mut Reg<%s>;\n' % (name, t, addr, t))
    # (the same addresses as integers, for asm)
    f.write('\npub mod addr {\n')
    for name, t, addr in regs:
        f.write('    pub const %s: u16 = 0x%x;\n' % (name, addr))
    f.write('}\n\n')
    for name, n in sorted(consts.items()):
        t = 'u8' if n < 0x100 else 'u16' if n < 0x10000 else 'u32' if n < 1 << 32 else 'u64'
        f.write('pub const %s: %s = 0x%x;\n' % (name, t, n))
    f.write('\n// the __vector_N symbol of an interrupt (avr-libc ISR())\nmacro_rules! avr_vector {\n')
    for name, n in vectors:
        f.write('    (%s) => { "__vector_%d" };\n' % (name, n))
    f.write('}\n')
