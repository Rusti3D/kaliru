#!/usr/bin/env python3
# Generate src/rp2040/stage2.rs: the rp2040 flash "stage2" boot blocks (the .boot2 section of
# Kalico's rp2040 build), built from Kalico's lib/pico-sdk/rp2040/boot_stage2 sources with the
# commands of src/rp2040/Makefile (assemble, link with boot_stage2.ld, objcopy, pad_checksum),
# one per flash chip choice of src/rp2040/Kconfig.
#
#   gen_rp2040_stage2.py <kalico> <out.rs>
import os, re, subprocess, sys, tempfile

kalico, out = sys.argv[1:3]
lib = os.path.join(kalico, 'lib')
sdk = os.path.join(lib, 'pico-sdk')
stage2 = os.path.join(sdk, 'rp2040', 'boot_stage2')
# (the Kconfig flash chip choice, RP2040_STAGE2_FILE, RP2040_STAGE2_CLKDIV)
CHOICES = [('CONFIG_RP2040_FLASH_W25Q080', 'boot2_w25q080.S', 2),
           ('CONFIG_RP2040_FLASH_GENERIC_03', 'boot2_generic_03h.S', 4),
           ('CONFIG_RP2040_FLASH_GENERIC_03_CLKDIV8', 'boot2_generic_03h.S', 8)]
CFLAGS = ['-mcpu=cortex-m0plus', '-mthumb', '-DPICO_RP2040', '-I' + os.path.join(lib, 'cmsis-core'),
          '-I' + os.path.join(sdk, 'rp2040'), '-I' + sdk, '-I' + os.path.join(sdk, 'rp2040', 'cmsis_include')]


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(' '.join(cmd) + '\n' + r.stderr)


def build(src, clkdiv):
    with tempfile.TemporaryDirectory() as d:
        o = lambda n: os.path.join(d, n)
        run(['arm-none-eabi-gcc'] + CFLAGS + ['-I' + stage2, '-I' + os.path.join(stage2, 'asminclude'),
             '-DPICO_FLASH_SPI_CLKDIV=%d' % clkdiv, '-c', os.path.join(stage2, src), '-o', o('stage2raw1.o')])
        run(['arm-none-eabi-ld', o('stage2raw1.o'), '--script=' + os.path.join(stage2, 'boot_stage2.ld'),
             '-o', o('stage2raw.o')])
        run(['arm-none-eabi-objcopy', '-O', 'binary', o('stage2raw.o'), o('stage2raw.bin')])
        run([sys.executable, os.path.join(stage2, 'pad_checksum'), '-s', '0xffffffff', o('stage2raw.bin'),
             o('stage2.S')])
        text = open(o('stage2.S')).read()
    return [int(b, 16) for line in re.findall(r'^\.byte (.*)$', text, re.M) for b in line.split(', ')]


o = ['// Generated by tools/gen_rp2040_stage2.py from Kalico lib/pico-sdk/rp2040/boot_stage2: do not edit.',
     '// The flash stage2 boot block (src/rp2040/Makefile stage2.o, at the start of flash), built from',
     '// CONFIG_RP2040_STAGE2_FILE with PICO_FLASH_SPI_CLKDIV=CONFIG_RP2040_STAGE2_CLKDIV.',
     'use crate::config::{CONFIG_RP2040_STAGE2_CLKDIV, CONFIG_RP2040_STAGE2_FILE};', '',
     '// (RP2040_STAGE2_FILE, RP2040_STAGE2_CLKDIV, the padded and checksummed block)',
     'const STAGE2: &[(&str, u32, [u8; 256])] = &[']
for choice, src, clkdiv in CHOICES:
    data = build(src, clkdiv)
    assert len(data) == 256
    o.append('    ("%s", %d, [' % (src, clkdiv))
    for j in range(0, 256, 16):
        o.append('        ' + ' '.join('0x%02x,' % b for b in data[j:j + 16]))
    o.append('    ]),')
o += ['];', '',
      'const fn str_eq(a: &str, b: &str) -> bool {',
      '    let (a, b) = (a.as_bytes(), b.as_bytes());',
      '    if a.len() != b.len() {',
      '        return false;',
      '    }',
      '    let mut i = 0;',
      '    while i < a.len() {',
      '        if a[i] != b[i] {',
      '            return false;',
      '        }',
      '        i += 1;',
      '    }',
      '    true',
      '}', '',
      'const fn lookup(file: &str, clkdiv: u32) -> [u8; 256] {',
      '    let mut i = 0;',
      '    while i < STAGE2.len() {',
      '        if str_eq(STAGE2[i].0, file) && STAGE2[i].1 == clkdiv {',
      '            return STAGE2[i].2;',
      '        }',
      '        i += 1;',
      '    }',
      '    panic!("no stage2 block for this RP2040_STAGE2_FILE / RP2040_STAGE2_CLKDIV");',
      '}', '',
      '#[unsafe(link_section = ".boot2")]',
      '#[used]',
      'static BOOT2: [u8; 256] = lookup(CONFIG_RP2040_STAGE2_FILE, CONFIG_RP2040_STAGE2_CLKDIV);']
open(out, 'w').write('\n'.join(o) + '\n')
print('%s: %d stage2 blocks' % (out, len(CHOICES)))
