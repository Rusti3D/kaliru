use crate::atsamd::internal::*;
use crate::sched::R;
use crate::{decl_constant_str, decl_init};

const PIN_CLOCK_OUT_LDC1612: u32 = GPIO('B', 11);
#[allow(dead_code)]
const FREQ_LDC1612: u32 = 30000000;
decl_constant_str!("RESERVE_PINS_LDC1612", "PB11");

fn setup_clock_out_ldc1612() {
    // PB11 is connected to GCLK5, and since our target clock is 25 MHz, we can
    // directly use our 25 MHz crystal to get a very stable output.

    gpio_peripheral(PIN_CLOCK_OUT_LDC1612, 'M', 0);
    unsafe { &*GCLK }.GENCTRL[5].reg.write(GCLK_GENCTRL_SRC_XOSC0 | GCLK_GENCTRL_GENEN | GCLK_GENCTRL_OE);
}

const PIN_CLOCK_OUT_TMC2240: u32 = GPIO('B', 13);
const FREQ_TMC2240: u32 = 16000000;
decl_constant_str!("RESERVE_PINS_TMC2240", "PB13");

fn setup_clock_out_tmc2240() {
    // Target clock is 16 MHz, exactly one third of the peripheral clock
    // generated by PLL1. Set up GCLK7 and output it on the pin.

    gpio_peripheral(PIN_CLOCK_OUT_TMC2240, 'M', 0);
    unsafe { &*GCLK }.GENCTRL[7].reg.write(
        GCLK_GENCTRL_SRC_DPLL1 | GCLK_GENCTRL_GENEN | GCLK_GENCTRL_IDC | GCLK_GENCTRL_OE | GCLK_GENCTRL_DIV(96000000 / FREQ_TMC2240),
    );
}

const PIN_CLOCK_OUT_LOADCELL: u32 = GPIO('B', 16);
const FREQ_LOADCELL: u32 = 8000000;
decl_constant_str!("RESERVE_PINS_LOADCELL", "PB16");

fn setup_clock_out_loadcell() {
    // Target clock is 8 MHz, exactly one sixth of the peripheral clock
    // generated by PLL1. Set up GCLK2 and output it on the pin.

    gpio_peripheral(PIN_CLOCK_OUT_LOADCELL, 'M', 0);
    unsafe { &*GCLK }.GENCTRL[2].reg.write(
        GCLK_GENCTRL_SRC_DPLL1 | GCLK_GENCTRL_GENEN | GCLK_GENCTRL_IDC | GCLK_GENCTRL_OE | GCLK_GENCTRL_DIV(96000000 / FREQ_LOADCELL),
    );
}

pub fn external_clocks_init() -> R {
    setup_clock_out_ldc1612();
    setup_clock_out_tmc2240();
    setup_clock_out_loadcell();
    Ok(())
}
decl_init!(external_clocks_init);
